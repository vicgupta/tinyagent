package tinygo

import (
	"bytes"
	"context"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// MaxSourceBytes caps the Go source of one module.
const MaxSourceBytes = 4 << 20

// PDKFile is the helper file added to every build. It gives the module
// input() and output() over the Extism kernel and an empty main, so plugin
// source needs no third-party imports (builds run offline).
const PDKFile = "zz_tinyagent_pdk.go"

const pdkSource = `// Code generated by tinyagent. DO NOT EDIT.

package main

//go:wasmimport extism:host/env input_length
func tinyagentInputLength() uint64

//go:wasmimport extism:host/env input_load_u8
func tinyagentInputLoadU8(off uint64) uint32

//go:wasmimport extism:host/env alloc
func tinyagentAlloc(n uint64) uint64

//go:wasmimport extism:host/env store_u8
func tinyagentStoreU8(off uint64, v uint32)

//go:wasmimport extism:host/env output_set
func tinyagentOutputSet(off, n uint64)

// input returns the tool call's arguments JSON.
func input() []byte {
	n := tinyagentInputLength()
	b := make([]byte, n)
	for i := uint64(0); i < n; i++ {
		b[i] = byte(tinyagentInputLoadU8(i))
	}
	return b
}

// output sets the tool result.
func output(b []byte) {
	off := tinyagentAlloc(uint64(len(b)))
	for i, c := range b {
		tinyagentStoreU8(off+uint64(i), uint32(c))
	}
	tinyagentOutputSet(off, uint64(len(b)))
}

func main() {}
`

// Runner runs argv in workdir with env, writing its output to out.
// TinyAgent passes one that confines the command with the OS sandbox:
// writes only inside writable, no network.
type Runner func(ctx context.Context, writable, workdir string, argv, env []string, out io.Writer) error

// Sources reads the .go files directly in dir (no subdirectories, tests
// or go.mod) and returns them with their combined sha256.
func Sources(dir string) (map[string][]byte, string, error) {
	ents, err := os.ReadDir(dir)
	if err != nil {
		return nil, "", err
	}
	files := map[string][]byte{}
	var names []string
	total := 0
	for _, e := range ents {
		n := e.Name()
		if !strings.HasSuffix(n, ".go") || strings.HasSuffix(n, "_test.go") || n == PDKFile {
			continue
		}
		if !e.Type().IsRegular() {
			return nil, "", fmt.Errorf("%s is not a regular file", n)
		}
		b, err := os.ReadFile(filepath.Join(dir, n))
		if err != nil {
			return nil, "", err
		}
		if total += len(b); total > MaxSourceBytes {
			return nil, "", fmt.Errorf("go source is larger than %d bytes", MaxSourceBytes)
		}
		files[n] = b
		names = append(names, n)
	}
	if len(files) == 0 {
		return nil, "", fmt.Errorf("no .go files in %s", dir)
	}
	sort.Strings(names)
	h := sha256.New()
	h.Write([]byte("tinygo " + Version + "\x00"))
	for _, n := range names {
		fmt.Fprintf(h, "%s\x00%d\x00", n, len(files[n]))
		h.Write(files[n])
	}
	return files, hex.EncodeToString(h.Sum(nil)), nil
}

// Build compiles a module's Go source (package main, standard library
// only, exports marked //go:wasmexport) to WebAssembly with tinygo for
// wasip1, in a fresh temp directory, through run. run must not be nil: the
// source may be agent-written, so it never builds unconfined.
func Build(ctx context.Context, tinygoBin string, files map[string][]byte, run Runner) ([]byte, error) {
	if run == nil {
		return nil, errors.New("tinygo: building plugin source needs the OS sandbox, which is unavailable")
	}
	dir, err := os.MkdirTemp("", "tinyagent-tinygo-")
	if err != nil {
		return nil, err
	}
	defer os.RemoveAll(dir)
	src := filepath.Join(dir, "src")
	for _, d := range []string{src, filepath.Join(dir, "home"), filepath.Join(dir, "gocache"), filepath.Join(dir, "gopath")} {
		if err := os.MkdirAll(d, 0o755); err != nil {
			return nil, err
		}
	}
	for n, b := range files {
		if filepath.Base(n) != n || !strings.HasSuffix(n, ".go") || n == PDKFile {
			return nil, fmt.Errorf("tinygo: invalid source file name %q", n)
		}
		if err := os.WriteFile(filepath.Join(src, n), b, 0o644); err != nil {
			return nil, err
		}
	}
	os.WriteFile(filepath.Join(src, PDKFile), []byte(pdkSource), 0o644)
	os.WriteFile(filepath.Join(src, "go.mod"), []byte("module tinyagent.plugin/module\n\ngo 1.22\n"), 0o644)
	out := filepath.Join(dir, "module.wasm")
	argv := []string{tinygoBin, "build", "-o", out, "-target=wasip1", "-buildmode=c-shared", "-no-debug", "-opt=z", "-scheduler=none", "."}
	env := []string{
		"PATH=" + os.Getenv("PATH"),
		"HOME=" + filepath.Join(dir, "home"),
		"XDG_CACHE_HOME=" + filepath.Join(dir, "home", ".cache"),
		"GOCACHE=" + filepath.Join(dir, "gocache"),
		"GOPATH=" + filepath.Join(dir, "gopath"),
		"GOPROXY=off", "GOFLAGS=-mod=mod", "GOTOOLCHAIN=local", "GOWORK=off", "GO111MODULE=on", "CGO_ENABLED=0",
		"TMPDIR=" + dir,
	}
	var buf bytes.Buffer
	if err := run(ctx, dir, src, argv, env, &buf); err != nil {
		msg := strings.TrimSpace(buf.String())
		if len(msg) > 4000 {
			msg = msg[:4000] + "..."
		}
		return nil, fmt.Errorf("tinygo build failed: %v: %s", err, msg)
	}
	return os.ReadFile(out)
}
